#!/bin/bash
# MagicMirror asset build script
# Concatenates CSS + JS into single bundles to reduce HTTP requests
# Run: bash scripts/build.sh
# Output: static/css/bundle.css, static/js/bundle.js

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR/.."

echo "Building MagicMirror asset bundles..."

# ── CSS Bundle ────────────────────────────────────────────────────────────────
CSS_BUNDLE="static/css/bundle.css"
echo "/* MagicMirror CSS Bundle — auto-generated by build.sh */" > "$CSS_BUNDLE"
echo "/* DO NOT EDIT — edit individual files instead */" >> "$CSS_BUNDLE"
echo "" >> "$CSS_BUNDLE"

# Core CSS first
cat "static/css/main.css" >> "$CSS_BUNDLE"
echo "" >> "$CSS_BUNDLE"

# Widget CSS (auto-discover)
for dir in widgets/*/; do
  name=$(basename "$dir")
  [[ "$name" == _* ]] && continue
  css="$dir${name}.css"
  [ -f "$css" ] && {
    echo "/* ── Widget: $name ── */" >> "$CSS_BUNDLE"
    cat "$css" >> "$CSS_BUNDLE"
    echo "" >> "$CSS_BUNDLE"
  }
done

echo "  ✓ $CSS_BUNDLE ($(wc -c < "$CSS_BUNDLE") bytes)"

# ── JS Bundle ─────────────────────────────────────────────────────────────────
JS_BUNDLE="static/js/bundle.js"
echo "/* MagicMirror JS Bundle — auto-generated by build.sh */" > "$JS_BUNDLE"
echo "/* DO NOT EDIT — edit individual files instead */" >> "$JS_BUNDLE"
echo "" >> "$JS_BUNDLE"

# WS client first
cat "static/js/ws.js" >> "$JS_BUNDLE"
echo "" >> "$JS_BUNDLE"

# Widget JS (auto-discover, same order as CSS)
for dir in widgets/*/; do
  name=$(basename "$dir")
  [[ "$name" == _* ]] && continue
  js="$dir${name}.js"
  [ -f "$js" ] && {
    echo "/* ── Widget: $name ── */" >> "$JS_BUNDLE"
    cat "$js" >> "$JS_BUNDLE"
    echo "" >> "$JS_BUNDLE"
  }
done

# App JS last (needs widget classes registered first)
cat "static/js/app.js" >> "$JS_BUNDLE"
echo "" >> "$JS_BUNDLE"

echo "  ✓ $JS_BUNDLE ($(wc -c < "$JS_BUNDLE") bytes)"
echo ""
echo "Build complete! To use bundles, update index.html to load:"
echo "  /css/bundle.css instead of /css/main.css"
echo "  /js/bundle.js instead of the dynamic widget loader"
